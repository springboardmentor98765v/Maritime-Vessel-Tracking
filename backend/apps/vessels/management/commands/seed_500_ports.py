class Command(BaseCommand):
    help = "Seeds the database with ~500 realistic global ports."

    def add_arguments(self, parser):
        parser.add_argument(
            "--clear", action="store_true",
            help="Delete all existing ports before seeding",
        )

    def handle(self, *args, **options):
        now = timezone.now()

        if options["clear"]:
            self.stdout.write("Deleting all existing ports and traffic history...")
            PortTrafficHistory.objects.all().delete()
            Port.objects.all().delete()
            self.stdout.write(self.style.WARNING("Cleared."))

        self.stdout.write(f"Seeding up to {len(PORT_DATA)} ports...")
        created_count = 0
        port_objs = []

        bulk = []
        existing_names = set(Port.objects.values_list("name", flat=True))

        for name, location, country, lat, lon in PORT_DATA:
            if name in existing_names:
                continue
            score = round(random.uniform(5.0, 98.0), 1)
            avg_wait = round(random.uniform(2.0, 96.0), 1)
            arrivals = random.randint(2, 120)
            departures = random.randint(2, 115)
            bulk.append(Port(
                name=name,
                location=location,
                country=country,
                congestion_score=score,
                avg_wait_time=avg_wait,
                arrivals=arrivals,
                departures=departures,
                last_update=now - timedelta(minutes=random.randint(1, 240)),
                last_analytics_update=now - timedelta(minutes=random.randint(30, 480)),
            ))

        if bulk:
            created = Port.objects.bulk_create(bulk, ignore_conflicts=True)
            created_count = len(created)
            port_objs = created
        
        # Seed traffic history for each created port (last 7 days, every 6 hours)
        self.stdout.write("Generating port traffic history...")
        history_bulk = []
        all_ports = list(Port.objects.all())
        for port in all_ports:
            for hours_ago in range(0, 7 * 24, 6):
                ts = now - timedelta(hours=hours_ago)
                history_bulk.append(PortTrafficHistory(
                    port=port,
                    timestamp=ts,
                    arrivals=random.randint(1, 30),
                    departures=random.randint(1, 28),
                    congestion_score=round(random.uniform(5.0, 98.0), 1),
                ))

        PortTrafficHistory.objects.bulk_create(history_bulk, ignore_conflicts=True)

        self.stdout.write(self.style.SUCCESS(
            f"\nDone!\n"
            f"  Ports created : {created_count}\n"
            f"  Total ports   : {Port.objects.count()}\n"
            f"  Traffic records seeded: {len(history_bulk)}\n"
        ))
